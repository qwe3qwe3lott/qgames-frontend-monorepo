import {z} from 'zod';

/**
 * Логин: 3–32 символа, строчная латиница, цифры, `_` и `-` (контракт — `LoginRules`
 * бэкенда). Задаётся при регистрации и не меняется. Правило повторено здесь ради
 * понятного русского сообщения вместо шаблона регулярного выражения.
 */
export const loginSchema = z
  .string()
  .min(3)
  .max(32)
  .regex(/^[a-z0-9_-]+$/, {
    message: 'Только строчные латинские буквы, цифры, «_» и «-»',
  });
